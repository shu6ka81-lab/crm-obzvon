#!/usr/bin/env bash
# Включает защищённое соединение прямо на адресе сервера, без домена.
#
#   bash s.sh 62.109.16.153
#
# Зачем. Куки сессии выдаётся с пометкой «только по защищённому соединению»,
# и по обычному HTTP браузер её не сохраняет: вход проходит, а на следующей
# странице человека уже не узнают и возвращают на форму.
#
# Домену для настоящего сертификата нужно время на активацию зоны, а работать
# надо сегодня. Поэтому Caddy выпускает сертификат сам, своим внутренним
# центром. Соединение при этом полноценно зашифровано — не подтверждена только
# личность сайта. Браузер один раз предупредит: «Дополнительно» -> «Перейти».
#
# Это не замена настоящему сертификату: постороннему человеку такой сайт
# отличить от подделки нечем. Для своих на время — приемлемо, как постоянное
# решение — нет. Как только заработает домен: bash d.sh crm.adminshu6ka.ru

set -euo pipefail

ADDR="${1:-}"
if [[ -z "$ADDR" ]]; then
  echo "Укажите адрес: bash s.sh 62.109.16.153" >&2
  exit 1
fi

say() { printf '\n\033[1m==> %s\033[0m\n' "$1"; }

say "Проверка приложения"
if curl -fsS --max-time 10 http://127.0.0.1:3000/login >/dev/null 2>&1; then
  echo "отвечает на 127.0.0.1:3000"
else
  echo "приложение не отвечает — поднимите его: docker compose up -d" >&2
  exit 1
fi

say "Настройка обратного прокси"
cat > /etc/caddy/Caddyfile <<EOF
https://$ADDR {
    tls internal
    reverse_proxy 127.0.0.1:3000
    encode gzip
    header {
        X-Frame-Options DENY
        X-Content-Type-Options nosniff
        Referrer-Policy same-origin
    }
}

http://$ADDR {
    redir https://$ADDR{uri} permanent
}
EOF
systemctl enable caddy >/dev/null 2>&1 || true
systemctl restart caddy
sleep 3

if ! systemctl is-active --quiet caddy; then
  echo "Caddy не запустился. Журнал:" >&2
  journalctl -u caddy -n 30 --no-pager >&2
  exit 1
fi

say "Проверка"
# -k: сертификат свой, не от общепризнанного центра — проверку личности
# отключаем сознательно, иначе curl откажется соединяться.
CODE="$(curl -sk -o /dev/null -w '%{http_code}' --max-time 15 "https://$ADDR/login" 2>/dev/null || true)"
if [[ "$CODE" == '200' ]]; then
  echo "страница входа отдаётся по защищённому соединению"
else
  echo "ответ '${CODE:-нет}'. Журнал Caddy:" >&2
  journalctl -u caddy -n 20 --no-pager >&2
  exit 1
fi

cat <<EOF

============================================================
  Адрес системы:  https://$ADDR
============================================================

При первом заходе браузер предупредит, что сайт не подтверждён.
Это ожидаемо: сертификат выпущен самим сервером, а не сторонним
центром. Нажмите «Дополнительно» -> «Перейти на сайт».

Вход больше не будет слетать: соединение защищённое, и браузер
сохранит куки сессии.

Когда домен заработает, переключимся на настоящий сертификат:
  bash d.sh crm.adminshu6ka.ru

EOF
