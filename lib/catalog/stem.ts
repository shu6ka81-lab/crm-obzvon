/**
 * Приведение русского слова к основе.
 *
 * Зачем: индекс хранил слова как есть, и «карандаши» из запроса не находили
 * «карандаш» в прайсе. Слово выпадало из поиска целиком — 444 позиции с
 * карандашами оказывались невидимы, а по оставшемуся «простые» выигрывали
 * сушки. Ошибка выглядит как глупость подбора, а причина — в формах слов.
 *
 * Полный морфологический разбор здесь не нужен и вреден: наименования товаров
 * состоят из существительных и прилагательных в двух-трёх формах. Отрезаем
 * распространённые окончания, начиная с самых длинных.
 */

/** Окончания прилагательных и причастий. */
const ADJ = [
  'ими', 'ыми', 'его', 'ого', 'ему', 'ому', 'ых', 'их', 'ая', 'яя', 'ою', 'ею',
  'ое', 'ее', 'ые', 'ие', 'ый', 'ий', 'ой', 'ей', 'ым', 'им', 'ом', 'ем',
  'ую', 'юю',
]

/** Окончания существительных. */
const NOUN = [
  'иями', 'ями', 'ами', 'иях', 'иям', 'ием', 'ией', 'ов', 'ев', 'ье', 'ья',
  'ию', 'ия', 'ью', 'ям', 'ах', 'ях', 'ам', 'ом', 'ем', 'ой', 'ей', 'ии',
  'ие', 'ы', 'и', 'а', 'я', 'о', 'е', 'у', 'ю', 'ь', 'й',
]

/** Сначала длинные — иначе «иями» разберётся как «и» и основа выйдет кривой. */
const ENDINGS = [...new Set([...ADJ, ...NOUN])].sort((a, b) => b.length - a.length)

/**
 * Основа не короче четырёх букв. Иначе «море» превратится в «мор», «сок» и
 * «соки» разойдутся, а короткие слова начнут сливаться друг с другом.
 */
const MIN_STEM = 4

export function stem(word: string): string {
  if (word.length <= MIN_STEM) return word
  if (!/^[а-яё]+$/i.test(word)) return word

  for (const e of ENDINGS) {
    if (word.length - e.length >= MIN_STEM && word.endsWith(e)) {
      return word.slice(0, -e.length)
    }
  }
  return word
}

/**
 * Все допустимые основы слова. Обычно одна, но у части слов гласная в основе
 * появляется и пропадает: «перчатка» даёт «перчатк», а «перчаток» — «перчаток».
 *
 * Просто вырезать эту гласную нельзя: тогда «поток» и «потока» разойдутся.
 * Поэтому не выбираем одну основу, а возвращаем обе — совпадения по любой
 * достаточно, а лишний вариант почти никогда ни с чем не пересекается.
 */
export function stems(word: string): string[] {
  const base = stem(word)
  const out = [base]

  const m = base.match(/^(.*[а-яё])[ое](к|ц|н|л|р|м|в|т|ш|ж|ч|щ|б|п|д|г|з|с|ф|х)$/i)
  if (m && m[1].length + 1 >= MIN_STEM) out.push(m[1] + m[2])

  return out
}
