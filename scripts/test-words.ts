/**
 * Сумма прописью — проверка на местах, где обычно ошибаются:
 * тысячи женского рода, подростковые числа, окончания рублей.
 *
 * Запуск: npx tsx scripts/test-words.ts
 */
import { rublesInWords } from '../app/quote/[id]/pdf/words'

const CASES: [number, string][] = [
  [0, 'Ноль рублей 00 коп.'],
  [1, 'Один рубль 00 коп.'],
  [2, 'Два рубля 00 коп.'],
  [5, 'Пять рублей 00 коп.'],
  [11, 'Одиннадцать рублей 00 коп.'],
  [21, 'Двадцать один рубль 00 коп.'],
  [111, 'Сто одиннадцать рублей 00 коп.'],
  [1000, 'Одна тысяча рублей 00 коп.'],
  [2000, 'Две тысячи рублей 00 коп.'],
  [5000, 'Пять тысяч рублей 00 коп.'],
  [12000, 'Двенадцать тысяч рублей 00 коп.'],
  [15991.07, 'Пятнадцать тысяч девятьсот девяносто один рубль 07 коп.'],
  [1_000_000, 'Один миллион рублей 00 коп.'],
  [2_345_678.9, 'Два миллиона триста сорок пять тысяч шестьсот семьдесят восемь рублей 90 коп.'],
]

let bad = 0
for (const [n, want] of CASES) {
  const got = rublesInWords(n)
  const ok = got === want
  if (!ok) bad++
  console.log(`${ok ? '✓' : '✗'} ${String(n).padStart(12)}  ${got}`)
  if (!ok) console.log(`${' '.repeat(15)}ждали: ${want}`)
}

if (bad) {
  console.error(`\nне сошлось: ${bad} из ${CASES.length}`)
  process.exit(1)
}
console.log(`\nвсе ${CASES.length} проверок прошли`)
